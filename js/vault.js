/*
 * Evidence Vault — append-only, hash-chained, encrypted.
 * Every entry stores the SHA-256 of each file, a timestamp, and the hash of the previous entry.
 * Editing or removing any past entry breaks every later link, so tampering is detectable.
 * Exports a printable report with a Bharatiya Sakshya Adhiniyam s.63 certificate template.
 */
const Vault = (() => {
  const GENESIS = '0'.repeat(64);

  const canonical = e => JSON.stringify({ v: 1, createdAt: e.createdAt, platform: e.platform, url: e.url, handle: e.handle, desc: e.desc, seen: e.seen, files: e.files.map(f => f.sha256), prevHash: e.prevHash });
  const hashEntry = e => sha256(canonical(e));

  async function list() { return (await Store.all('evidence')).sort((a, b) => a.createdAt.localeCompare(b.createdAt)); }

  async function add({ platform, url, handle, desc, seen, files }) {
    const all = await list();
    const prevHash = all.length ? all[all.length - 1].entryHash : GENESIS;
    const fmeta = [];
    for (const f of files) {
      const buf = await f.arrayBuffer(), blobId = uid();
      await Store.putBlob(blobId, buf);
      fmeta.push({ name: f.name, type: f.type || 'application/octet-stream', size: f.size, sha256: await sha256(buf), blobId });
    }
    const e = { id: uid(), createdAt: new Date().toISOString(), platform, url, handle: (handle || '').trim(), desc, seen: seen || '', files: fmeta, prevHash };
    e.entryHash = await hashEntry(e);
    await Store.put('evidence', e.id, e);
    return e;
  }

  async function verify(entries) {
    let prev = GENESIS;
    for (let i = 0; i < entries.length; i++) {
      const e = entries[i];
      if (e.prevHash !== prev || (await hashEntry(e)) !== e.entryHash) return { ok: false, brokenAt: i };
      prev = e.entryHash;
    }
    return { ok: true, head: prev, count: entries.length };
  }

  const normHandle = h => (h || '').toLowerCase().replace(/^@/, '').trim();
  function linked(entries) {
    const g = {};
    entries.forEach(e => { const k = normHandle(e.handle); if (k) (g[k] = g[k] || []).push(e); });
    return Object.entries(g).filter(([, v]) => v.length > 1).map(([handle, items]) => ({ handle, items }));
  }

  async function reportHtml(entries, who = {}) {
    const v = await verify(entries);
    const rows = [];
    for (const [i, e] of entries.entries()) {
      let imgs = '';
      for (const f of e.files) if (/^image\//.test(f.type)) {
        const buf = await Store.getBlob(f.blobId);
        if (buf) imgs += `<img src="${await blobToDataURL(new Blob([buf], { type: f.type }))}" alt="">`;
      }
      rows.push(`<section class="e"><h3>Exhibit ${i + 1}: ${esc(e.platform)}${e.handle ? ' · ' + esc(e.handle) : ''}</h3>
        <table><tr><th>Recorded in vault (UTC)</th><td>${esc(e.createdAt)}</td></tr>
        ${e.seen ? `<tr><th>Content seen / received at</th><td>${esc(e.seen)}</td></tr>` : ''}
        <tr><th>URL / location</th><td>${esc(e.url || '—')}</td></tr><tr><th>Description</th><td>${esc(e.desc)}</td></tr>
        <tr><th>Previous entry hash</th><td class="m">${e.prevHash}</td></tr><tr><th>Entry hash (SHA-256)</th><td class="m">${e.entryHash}</td></tr>
        ${e.files.map(f => `<tr><th>File</th><td>${esc(f.name)} (${f.size} bytes)<br><span class="m">SHA-256: ${f.sha256}</span></td></tr>`).join('')}</table>
        <div class="imgs">${imgs}</div></section>`);
    }
    const hashes = entries.flatMap(e => e.files.map(f => `${f.name}: ${f.sha256}`)).join('\n');
    return `<!doctype html><html><head><meta charset="utf-8"><title>Kavach Evidence Report</title><style>
      body{font:14px/1.55 Georgia,serif;color:#1b1220;max-width:820px;margin:28px auto;padding:0 20px}h1{font-size:26px;margin:0}h2{border-bottom:2px solid #8E2A5B;padding-bottom:4px;margin-top:34px}
      .bar{background:#2A1235;color:#fff;padding:14px 18px;border-radius:10px;display:flex;justify-content:space-between;align-items:center;margin-bottom:18px}
      table{width:100%;border-collapse:collapse;margin:8px 0}th,td{border:1px solid #d9cfd9;padding:6px 9px;text-align:left;vertical-align:top}th{width:200px;background:#faf3f6;font-family:sans-serif;font-size:12px}
      .m{font-family:ui-monospace,monospace;font-size:11px;word-break:break-all}.e{page-break-inside:avoid;margin-bottom:22px}.imgs img{max-width:48%;margin:4px;border:1px solid #ddd}
      .ok{background:#e3f3ef;border:1px solid #1F7A6D;padding:10px 14px;border-radius:8px}.bad{background:#fce8ea;border:1px solid #C5283D;padding:10px 14px;border-radius:8px}
      pre{white-space:pre-wrap;background:#faf3f6;padding:12px;border-radius:8px}button{padding:9px 16px;border-radius:99px;border:0;background:#E4572E;color:#fff;font-weight:700;cursor:pointer}@media print{.noprint{display:none}}</style></head><body>
      <div class="bar"><div><h1 style="color:#fff">Digital Evidence Report</h1><small>Generated by Kavach · ${new Date().toISOString()}</small></div><button class="noprint" onclick="print()">Print / Save as PDF</button></div>
      <p><b>Prepared for:</b> ${esc(who.name || 'Complainant (name withheld)')} &nbsp; <b>Exhibits:</b> ${entries.length}</p>
      <div class="${v.ok ? 'ok' : 'bad'}"><b>Integrity check:</b> ${v.ok ? `all ${v.count} entries form an unbroken SHA-256 hash chain. Chain head: <span class="m">${v.head}</span>` : `chain BROKEN at exhibit ${v.brokenAt + 1}. Records may have been altered.`}</div>
      <h2>Exhibits</h2>${rows.join('') || '<p>No entries.</p>'}
      <h2>Annexure A: How to verify this report</h2>
      <p>1. For each file, compute its SHA-256 (<code>sha256sum file</code> on Linux/macOS, <code>certutil -hashfile file SHA256</code> on Windows) and compare it with the value above. 2. Each exhibit's “entry hash” is the SHA-256 of its recorded fields plus the previous entry hash; altering any exhibit changes every later hash. 3. The chain head above can be independently timestamped (for example, e-mailed to a third party) to fix the latest state at a point in time.</p>
      <h2>Annexure B: Certificate for electronic records (template)</h2>
      <p><i>Template for a certificate under Section 63(4)(c) of the Bharatiya Sakshya Adhiniyam, 2023 (which replaced Section 65B of the Indian Evidence Act). Have a lawyer review and complete it. It must be signed by the person in charge of the device and, where required, an expert.</i></p>
      <pre>CERTIFICATE
I, ____________________ (name), son/daughter/wife of ____________________, residing at ____________________, do hereby certify:
1. I am the person who owns / is in lawful control of the device(s): ____________________ used to create and store the electronic record(s) described below.
2. The computer/device was operating properly during the relevant period, and the electronic record(s) were produced in the ordinary course of my use of it.
3. The information in the record(s) is a true reproduction of what was received/displayed on ____________________ (platform) on ____________________ (date/time).
4. The record(s) are identified by the following SHA-256 hash values:
${hashes || '(none)'}
Date: ____________  Place: ____________        Signature: ____________________

PART B (EXPERT, if applicable): ____________________</pre>
      <p style="color:#6b5a72;font-size:12px">Kavach is a self-help tool, not a law firm. This report supports a complaint; it does not guarantee admissibility. Original files should be preserved.</p></body></html>`;
  }

  return { list, add, verify, linked, reportHtml, GENESIS };
})();

